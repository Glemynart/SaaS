#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

log() {
  printf 'backup-set-roundtrip: %s\n' "$*"
}

fail() {
  log "ERROR: $*"
  exit 1
}

# This test writes only to the disposable PostgreSQL service created by this
# GitHub Actions job and a second Docker container isolated from every network.
if [[ "${GITHUB_ACTIONS:-}" != "true" || "${CI:-}" != "true" ]]; then
  fail "run only inside GitHub Actions with its disposable PostgreSQL service"
fi

POSTGRES_SERVICE_ID="${POSTGRES_SERVICE_ID:-}"
if [[ ! "$POSTGRES_SERVICE_ID" =~ ^[[:xdigit:]]{12,64}$ ]]; then
  fail "GitHub PostgreSQL service container ID is unavailable"
fi
if ! image=$(docker inspect --format '{{.Config.Image}}' "$POSTGRES_SERVICE_ID" 2>/dev/null) || [[ "$image" != "postgres:17" ]]; then
  fail "source container is not the disposable PostgreSQL 17 service"
fi
if ! running=$(docker inspect --format '{{.State.Running}}' "$POSTGRES_SERVICE_ID" 2>/dev/null) || [[ "$running" != "true" ]]; then
  fail "PostgreSQL service is not running"
fi
if ! source_label=$(docker inspect --format '{{index .Config.Labels "dusema.backup.environment"}}' "$POSTGRES_SERVICE_ID" 2>/dev/null) || [[ "$source_label" != "staging" ]]; then
  fail "PostgreSQL service is not labeled as disposable staging"
fi
if ! docker exec "$POSTGRES_SERVICE_ID" pg_isready --username postgres --dbname postgres >/dev/null 2>&1; then
  fail "PostgreSQL service is not ready"
fi
if [[ ! "${GITHUB_RUN_ID:-}" =~ ^[0-9]+$ || ! "${GITHUB_RUN_ATTEMPT:-}" =~ ^[0-9]+$ ]]; then
  fail "GitHub run identity is unavailable"
fi

readonly SOURCE_DATABASE="backup_set_source_${GITHUB_RUN_ID}_${GITHUB_RUN_ATTEMPT}"
readonly TARGET_DATABASE="dusema_recovery_set_${GITHUB_RUN_ID}_${GITHUB_RUN_ATTEMPT}"
readonly TARGET_CONTAINER_NAME="dusema-recovery-set-test-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}"
readonly WORK_ROOT="$(realpath -e -- "${RUNNER_TEMP:-${TMPDIR:-/tmp}}")"
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P) || fail "could not resolve script directory"
WORK_DIR=""
GNUPGHOME=""
TARGET_CONTAINER_ID=""
SOURCE_DATABASE_CREATED=0

cleanup() {
  local status=$?
  local cleanup_failed=0
  trap - EXIT

  if (( SOURCE_DATABASE_CREATED != 0 )); then
    if ! docker exec "$POSTGRES_SERVICE_ID" dropdb --if-exists --username postgres "$SOURCE_DATABASE" >/dev/null 2>&1; then
      cleanup_failed=1
    fi
  fi

  if [[ -n "$TARGET_CONTAINER_ID" ]] && docker inspect "$TARGET_CONTAINER_ID" >/dev/null 2>&1; then
    docker stop "$TARGET_CONTAINER_ID" >/dev/null 2>&1 || cleanup_failed=1
  fi

  if [[ -n "$WORK_DIR" ]]; then
    case "$WORK_DIR" in
      "${WORK_ROOT%/}"/dusema-backup-set-roundtrip.*)
        if [[ -d "$WORK_DIR" && ! -L "$WORK_DIR" ]]; then
          rm -rf -- "$WORK_DIR" 2>/dev/null || cleanup_failed=1
        else
          cleanup_failed=1
        fi
        ;;
      *) cleanup_failed=1 ;;
    esac
  fi

  if (( cleanup_failed != 0 )); then
    log "ERROR: disposable test resource cleanup failed"
    if (( status == 0 )); then status=1; fi
  fi
  exit "$status"
}

for binary in awk bash chmod cp date docker env gpg grep mkdir mktemp od python3 realpath rm sha256sum sleep stat tar tr; do
  command -v "$binary" >/dev/null 2>&1 || fail "required executable is unavailable: ${binary}"
done

WORK_DIR=$(mktemp -d "${WORK_ROOT%/}/dusema-backup-set-roundtrip.XXXXXX") || fail "could not create a private test directory"
GNUPGHOME="${WORK_DIR%/}/gnupg"
MOCK_BIN="${WORK_DIR%/}/mock-bin"
MOCK_OBJECT_STORE="${WORK_DIR%/}/mock-object-store"
MOCK_UPLOAD_LOG="${WORK_DIR%/}/mock-uploads.log"
UPLOADS_ROOT="${WORK_DIR%/}/source-uploads"
TMP_PARENT="${WORK_DIR%/}/encrypted-work"
SET_WORK_PARENT="${WORK_DIR%/}/set-work"
RESTORE_PARENT="${WORK_DIR%/}/restored-uploads"
RESTORE_WORK_PARENT="${WORK_DIR%/}/restore-work"
RESTORE_TMP_ROOT="${WORK_DIR%/}/restore-tmp"
TARGET_CONTAINER_ID=""
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP

mkdir -m 0700 -- "$GNUPGHOME" "$MOCK_BIN" "$MOCK_OBJECT_STORE" "$UPLOADS_ROOT" \
  "$TMP_PARENT" "$SET_WORK_PARENT" "$RESTORE_PARENT" "$RESTORE_WORK_PARENT" "$RESTORE_TMP_ROOT" \
  || fail "could not prepare private test directories"
: >"$MOCK_UPLOAD_LOG"

log "setup: creating an isolated source database and synthetic uploads tree"
docker exec "$POSTGRES_SERVICE_ID" createdb --username postgres "$SOURCE_DATABASE" \
  >/dev/null 2>"${WORK_DIR%/}/createdb.stderr" || fail "could not create the synthetic source database"
SOURCE_DATABASE_CREATED=1
if ! docker exec -i "$POSTGRES_SERVICE_ID" psql --no-psqlrc --username postgres --dbname "$SOURCE_DATABASE" --set ON_ERROR_STOP=1 \
  >/dev/null 2>"${WORK_DIR%/}/fixture.stderr" <<'SQL'
CREATE TABLE backup_set_probe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_key TEXT NOT NULL UNIQUE,
  metadata JSONB NOT NULL,
  payload BYTEA NOT NULL
);

INSERT INTO backup_set_probe (storage_key, metadata, payload) VALUES
  ('employees/employee-01/contract.txt', '{"version":1,"active":true}'::jsonb, decode('00ff807f', 'hex')),
  ('policies/retention.txt', '{"version":2,"active":false}'::jsonb, decode('00010203', 'hex'));
SQL
then
  fail "could not prepare synthetic database fixture"
fi
mkdir -m 0700 -- "${UPLOADS_ROOT%/}/employees/employee-01" "${UPLOADS_ROOT%/}/policies" \
  || fail "could not prepare synthetic uploads directories"
printf 'synthetic contract bytes\n' >"${UPLOADS_ROOT%/}/employees/employee-01/contract.txt"
printf 'synthetic retention policy\n' >"${UPLOADS_ROOT%/}/policies/retention.txt"

key_user_id="backup-set-roundtrip-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}@example.invalid"
if ! gpg --no-options --homedir "$GNUPGHOME" --batch --pinentry-mode loopback --passphrase '' \
  --quick-generate-key "$key_user_id" rsa2048 encrypt 1d \
  >/dev/null 2>"${WORK_DIR%/}/gpg-keygen.stderr"; then
  fail "could not create an ephemeral encryption and recovery key"
fi
if ! fingerprint=$(gpg --no-options --homedir "$GNUPGHOME" --batch --with-colons \
  --list-keys "$key_user_id" 2>"${WORK_DIR%/}/gpg-list.stderr" | awk -F: '$1 == "fpr" { print $10; exit }'); then
  fail "could not read the ephemeral key fingerprint"
fi
if [[ ! "$fingerprint" =~ ^[[:xdigit:]]{40,64}$ ]]; then
  fail "ephemeral key fingerprint is invalid"
fi

cat >"${MOCK_BIN%/}/oci" <<'MOCK_OCI'
#!/usr/bin/env bash
set -Eeuo pipefail
[[ "${1:-}" == "os" && "${2:-}" == "object" && "${3:-}" == "put" ]]
shift 3
name=""
file=""
bucket=""
profile=""
checksum=0
no_overwrite=0
while (($#)); do
  case "$1" in
    --name) name="$2"; shift 2 ;;
    --file) file="$2"; shift 2 ;;
    --bucket-name) bucket="$2"; shift 2 ;;
    --profile) profile="$2"; shift 2 ;;
    --namespace-name|--region) shift 2 ;;
    --verify-checksum) checksum=1; shift ;;
    --no-overwrite) no_overwrite=1; shift ;;
    *) exit 94 ;;
  esac
done
[[ "$bucket" == "dusema-staging-backups" && "$profile" == "ci-test" ]]
[[ "$name" == backup-sets/* && "$name" != *".."* ]]
[[ -s "$file" && "$checksum" == 1 && "$no_overwrite" == 1 ]]
destination="${MOCK_OBJECT_STORE%/}/${name}"
[[ ! -e "$destination" && ! -L "$destination" ]]
mkdir -p -- "$(dirname -- "$destination")"
cp -- "$file" "$destination"
printf '%s\n' "$name" >>"$MOCK_UPLOAD_LOG"
MOCK_OCI
chmod 0700 -- "${MOCK_BIN%/}/oci" || fail "could not prepare the mocked object-storage client"

log "backup: coordinating real PostgreSQL and uploads artifacts with mocked OCI"
if ! backup_output=$(env \
  BACKUP_SET_ENVIRONMENT=staging \
  BACKUP_SET_ISOLATED_CONFIRMED=true \
  UPLOADS_QUIESCED=true \
  BACKUP_SET_APPLICATION_REVISION=aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa \
  BACKUP_SET_STORAGE_PROVIDER=synthetic-ci \
  BACKUP_SET_PG_CONTAINER="$POSTGRES_SERVICE_ID" \
  BACKUP_SET_PG_DATABASE="$SOURCE_DATABASE" \
  BACKUP_SET_PG_ROLE=postgres \
  UPLOADS_ROOT="$UPLOADS_ROOT" \
  TMP_PARENT="$TMP_PARENT" \
  BACKUP_SET_WORK_PARENT="$SET_WORK_PARENT" \
  GNUPGHOME="$GNUPGHOME" \
  RECOVERY_RECIPIENT_FINGERPRINT="$fingerprint" \
  OCI_NAMESPACE=ci-test \
  OCI_BUCKET=dusema-staging-backups \
  OCI_REGION=ci-test-1 \
  OCI_OBJECT_PREFIX=backup-sets \
  OCI_UPLOAD_PROFILE=ci-test \
  OCI_CLI="${MOCK_BIN%/}/oci" \
  MOCK_OBJECT_STORE="$MOCK_OBJECT_STORE" \
  MOCK_UPLOAD_LOG="$MOCK_UPLOAD_LOG" \
  bash "${SCRIPT_DIR%/}/backup-set.sh" 2>&1); then
  printf '%s\n' "$backup_output"
  fail "coordinated synthetic backup failed"
fi
printf '%s\n' "$backup_output"
if ! readarray -t marker_fields < <(python3 - "$backup_output" <<'PY'
import re
import sys

pattern = re.compile(
    r"complete: backup set marker published backup_set_id=([0-9]{8}T[0-9]{6}Z-[0-9a-f]{16}) "
    r"manifest_sha256=([0-9a-f]{64}) manifest_bytes=([0-9]+)"
)
match = pattern.search(sys.argv[1])
if match is None:
    raise SystemExit("backup coordinator did not report a complete manifest marker")
print("\n".join(match.groups()))
PY
); then
  fail "could not parse the coordinated backup completion marker"
fi
if [[ "${#marker_fields[@]}" != 3 ]]; then
  fail "coordinated backup completion marker fields are incomplete"
fi
BACKUP_SET_ID="${marker_fields[0]}"
manifest_sha256="${marker_fields[1]}"
manifest_bytes="${marker_fields[2]}"
set_object_dir="${MOCK_OBJECT_STORE%/}/backup-sets/${BACKUP_SET_ID}"
manifest_file="${set_object_dir%/}/manifest.json.gpg"
postgres_file="${set_object_dir%/}/postgres.dump.gpg"
uploads_file="${set_object_dir%/}/uploads.tar.gpg"
if [[ ! -s "$manifest_file" || ! -s "$postgres_file" || ! -s "$uploads_file" ]]; then
  fail "mock OCI did not retain all three encrypted set objects"
fi
if [[ "$(stat -c '%s' -- "$manifest_file")" != "$manifest_bytes" ]]; then
  fail "recorded manifest byte count does not match the uploaded ciphertext"
fi
if [[ "$(sha256sum -- "$manifest_file" | awk '{print $1}')" != "$manifest_sha256" ]]; then
  fail "recorded manifest checksum does not match the uploaded ciphertext"
fi
if ! python3 - "$MOCK_OBJECT_STORE" "$MOCK_UPLOAD_LOG" "$BACKUP_SET_ID" <<'PY'
import pathlib
import sys

store = pathlib.Path(sys.argv[1])
log_path = pathlib.Path(sys.argv[2])
set_id = sys.argv[3]
expected = [
    f"backup-sets/{set_id}/postgres.dump.gpg",
    f"backup-sets/{set_id}/uploads.tar.gpg",
    f"backup-sets/{set_id}/manifest.json.gpg",
]
actual_objects = sorted(path.relative_to(store).as_posix() for path in store.rglob("*") if path.is_file())
actual_uploads = log_path.read_text(encoding="utf-8").splitlines()
if actual_objects != sorted(expected) or actual_uploads != expected:
    raise SystemExit("backup set objects were incomplete, duplicated, or not published marker-last")
PY
then
  fail "coordinated object set or marker-last publication order is invalid"
fi

log "setup: creating a disconnected PostgreSQL 17 restore container"
TARGET_CONTAINER_ID=$(docker run --detach --rm --name "$TARGET_CONTAINER_NAME" \
  --network none \
  --label 'dusema.recovery=isolated' \
  --env POSTGRES_PASSWORD=ci-only-backup-test \
  postgres:17 2>"${WORK_DIR%/}/restore-container.stderr") || fail "could not create isolated restore container"
if [[ ! "$TARGET_CONTAINER_ID" =~ ^[[:xdigit:]]{12,64}$ ]]; then
  fail "isolated restore container ID is invalid"
fi
target_ready=false
for attempt in {1..30}; do
  if docker exec "$TARGET_CONTAINER_ID" pg_isready --username postgres --dbname postgres >/dev/null 2>&1; then
    target_ready=true
    break
  fi
  sleep 1
done
if [[ "$target_ready" != true ]]; then
  fail "isolated PostgreSQL restore container did not become ready"
fi

RESTORE_DIR_NAME="dusema-uploads-restored-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}"
log "restore: validating the encrypted marker and restoring both set artifacts"
if ! restore_output=$(env \
  BACKUP_SET_ID="$BACKUP_SET_ID" \
  ENCRYPTED_MANIFEST_FILE="$manifest_file" \
  EXPECTED_MANIFEST_CIPHERTEXT_SHA256="$manifest_sha256" \
  ENCRYPTED_POSTGRES_FILE="$postgres_file" \
  ENCRYPTED_UPLOADS_FILE="$uploads_file" \
  RECOVERY_GNUPGHOME="$GNUPGHOME" \
  RESTORE_SET_NAMESPACE=ci-test \
  RESTORE_SET_BUCKET=dusema-staging-backups \
  RESTORE_SET_REGION=ci-test-1 \
  RESTORE_CONTAINER_ID="$TARGET_CONTAINER_ID" \
  RESTORE_DATABASE="$TARGET_DATABASE" \
  RESTORE_TMP_ROOT="$RESTORE_TMP_ROOT" \
  RESTORE_PARENT="$RESTORE_PARENT" \
  RESTORE_DIR_NAME="$RESTORE_DIR_NAME" \
  RESTORE_WORK_PARENT="$RESTORE_WORK_PARENT" \
  bash "${SCRIPT_DIR%/}/restore-backup-set.sh" 2>&1); then
  printf '%s\n' "$restore_output"
  fail "coordinated backup set restore failed"
fi
printf '%s\n' "$restore_output"
if [[ "$restore_output" != *"complete: both artifacts restored in isolated targets backup_set_id=${BACKUP_SET_ID}"* ]]; then
  fail "restore coordinator did not confirm the expected complete set"
fi

state_query=$(cat <<'SQL'
SELECT concat_ws(':',
  count(*)::text,
  md5(COALESCE(string_agg(
    id::text || '|' || storage_key || '|' || metadata::text || '|' || encode(payload, 'hex'),
    E'\n' ORDER BY id), '')),
  (SELECT last_value::text FROM backup_set_probe_id_seq),
  (SELECT is_called::text FROM backup_set_probe_id_seq)
)
FROM backup_set_probe;
SQL
)
if ! source_state=$(docker exec "$POSTGRES_SERVICE_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname "$SOURCE_DATABASE" --command "$state_query" \
  2>"${WORK_DIR%/}/source-state.stderr"); then
  fail "could not read synthetic source database state"
fi
if ! restored_state=$(docker exec "$TARGET_CONTAINER_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname "$TARGET_DATABASE" --command "$state_query" \
  2>"${WORK_DIR%/}/restored-state.stderr"); then
  fail "could not read restored database state"
fi
if [[ -z "$source_state" || "$source_state" != "$restored_state" ]]; then
  fail "restored PostgreSQL rows or identity sequence do not match the source"
fi

restored_uploads_root="${RESTORE_PARENT%/}/${RESTORE_DIR_NAME}"
docker exec "$TARGET_CONTAINER_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname "$TARGET_DATABASE" \
  --command 'SELECT storage_key FROM backup_set_probe ORDER BY storage_key;' \
  >"${WORK_DIR%/}/restored-references.txt" 2>"${WORK_DIR%/}/reference-query.stderr" \
  || fail "could not read restored database upload references"
if ! python3 - "$UPLOADS_ROOT" "$restored_uploads_root" "${WORK_DIR%/}/restored-references.txt" <<'PY'
import hashlib
import pathlib
import sys

source = pathlib.Path(sys.argv[1])
restored = pathlib.Path(sys.argv[2])
references = {line.strip() for line in pathlib.Path(sys.argv[3]).read_text(encoding="utf-8").splitlines() if line.strip()}

def file_hashes(root: pathlib.Path) -> dict[str, str]:
    return {
        path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in root.rglob("*")
        if path.is_file() and ".dusema-backup-meta" not in path.relative_to(root).parts
    }

source_files = file_hashes(source)
restored_files = file_hashes(restored)
if source_files != restored_files:
    raise SystemExit("restored uploads do not match the synthetic source tree")
if references != set(restored_files):
    raise SystemExit("restored PostgreSQL references do not match the restored upload keys")
PY
then
  fail "database and uploads recovery-set references do not match"
fi

log "PASS: coordinated PostgreSQL+uploads set restored; database rows/sequence and referenced files match"
