#!/usr/bin/env bash
set -Eeuo pipefail
umask 077

log() {
  printf 'backup-restore-roundtrip: %s\n' "$*"
}

fail() {
  log "ERROR: $*"
  exit 1
}

# This test writes only to the disposable PostgreSQL service created by this
# GitHub Actions job and a second Docker container isolated from every network.
if [[ "${GITHUB_ACTIONS:-}" != "true" || "${CI:-}" != "true" ]]; then
  fail "run only inside GitHub Actions with its disposable PostgreSQL service"
fi

POSTGRES_SERVICE_ID="${POSTGRES_SERVICE_ID:-}"
if [[ ! "$POSTGRES_SERVICE_ID" =~ ^[[:xdigit:]]{12,64}$ ]]; then
  fail "GitHub PostgreSQL service container ID is unavailable"
fi

if ! image=$(docker inspect --format '{{.Config.Image}}' "$POSTGRES_SERVICE_ID" 2>/dev/null) || [[ "$image" != "postgres:17" ]]; then
  fail "target is not the PostgreSQL 17 service container"
fi
if ! running=$(docker inspect --format '{{.State.Running}}' "$POSTGRES_SERVICE_ID" 2>/dev/null) || [[ "$running" != "true" ]]; then
  fail "PostgreSQL service is not running"
fi
if ! docker exec "$POSTGRES_SERVICE_ID" pg_isready --username postgres --dbname postgres >/dev/null 2>&1; then
  fail "PostgreSQL service is not ready"
fi

if [[ ! "${GITHUB_RUN_ID:-}" =~ ^[0-9]+$ || ! "${GITHUB_RUN_ATTEMPT:-}" =~ ^[0-9]+$ ]]; then
  fail "GitHub run identity is unavailable"
fi
readonly SOURCE_DATABASE="backup_source_${GITHUB_RUN_ID}_${GITHUB_RUN_ATTEMPT}"
readonly TARGET_DATABASE="dusema_recovery_${GITHUB_RUN_ID}_${GITHUB_RUN_ATTEMPT}"
readonly TARGET_CONTAINER_NAME="dusema-recovery-test-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}"
readonly WORK_ROOT="${RUNNER_TEMP:-${TMPDIR:-/tmp}}"
WORK_DIR=""
GNUPGHOME=""
TARGET_CONTAINER_ID=""
MOCK_BIN=""
MOCK_POSTGRES_CAPTURE=""

cleanup() {
  local status=$?
  local cleanup_failed=0
  trap - EXIT

  if [[ -n "$WORK_DIR" ]]; then
    case "$WORK_DIR" in
      "${WORK_ROOT%/}"/dusema-backup-restore.*)
        if [[ -d "$WORK_DIR" && ! -L "$WORK_DIR" ]]; then
          rm -rf -- "$WORK_DIR" 2>/dev/null || cleanup_failed=1
        else
          cleanup_failed=1
        fi
        ;;
      *) cleanup_failed=1 ;;
    esac
  fi

  if [[ -n "$TARGET_CONTAINER_ID" ]]; then
    docker stop "$TARGET_CONTAINER_ID" >/dev/null 2>&1 || cleanup_failed=1
  fi

  if (( cleanup_failed != 0 )); then
    log "ERROR: disposable test resource cleanup failed"
    if (( status == 0 )); then status=1; fi
  fi
  exit "$status"
}

WORK_DIR=$(mktemp -d "${WORK_ROOT%/}/dusema-backup-restore.XXXXXX") || fail "could not create a private test directory"
GNUPGHOME="${WORK_DIR%/}/gnupg"
MOCK_BIN="${WORK_DIR%/}/mock-bin"
MOCK_POSTGRES_CAPTURE="${WORK_DIR%/}/captured-postgres.dump.gpg"
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
trap 'exit 129' HUP
mkdir -m 0700 -- "$GNUPGHOME" "$MOCK_BIN" || fail "could not prepare private test directories"

for binary in chmod date docker gpg mktemp od python3 realpath rm sha256sum stat tr awk; do
  command -v "$binary" >/dev/null 2>&1 || fail "required executable is unavailable: ${binary}"
done

log "setup: creating disposable source and restore databases"
docker exec "$POSTGRES_SERVICE_ID" createdb --username postgres "$SOURCE_DATABASE" >/dev/null 2>"${WORK_DIR%/}/createdb-source.stderr" || fail "could not create source database"

TARGET_CONTAINER_ID=$(docker run --detach --rm --name "$TARGET_CONTAINER_NAME" \
  --network none \
  --label 'dusema.recovery=isolated' \
  --env POSTGRES_PASSWORD=ci-only-backup-test \
  postgres:17 2>"${WORK_DIR%/}/restore-container.stderr") || fail "could not create isolated restore container"
if [[ ! "$TARGET_CONTAINER_ID" =~ ^[[:xdigit:]]{12,64}$ ]]; then
  fail "isolated restore container ID is invalid"
fi
target_ready=false
for attempt in {1..30}; do
  if docker exec "$TARGET_CONTAINER_ID" pg_isready --username postgres --dbname postgres >/dev/null 2>&1; then
    target_ready=true
    break
  fi
  sleep 1
done
if [[ "$target_ready" != true ]]; then
  fail "isolated PostgreSQL restore container did not become ready"
fi

if ! docker exec -i "$POSTGRES_SERVICE_ID" psql --no-psqlrc --username postgres --dbname "$SOURCE_DATABASE" --set ON_ERROR_STOP=1 >/dev/null 2>"${WORK_DIR%/}/fixture.stderr" <<'SQL'
CREATE TABLE restore_probe (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL UNIQUE,
  metadata JSONB NOT NULL,
  payload BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

INSERT INTO restore_probe (label, metadata, payload, created_at) VALUES
  ('documento-á', '{"active":true,"version":3}'::jsonb, decode('00ff807f', 'hex'), '2026-10-29T12:34:56.123456Z'),
  ('memo-02', '{"active":false,"items":[1,2,3]}'::jsonb, decode('00010203', 'hex'), '2025-02-03T01:02:03.654321Z');
SQL
then
  fail "could not prepare synthetic backup fixture"
fi

key_user_id="restore-test-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}@example.invalid"
if ! gpg --no-options --homedir "$GNUPGHOME" --batch --pinentry-mode loopback --passphrase '' \
  --quick-generate-key "$key_user_id" rsa2048 encrypt 1d \
  >/dev/null 2>"${WORK_DIR%/}/gpg-keygen.stderr"; then
  fail "could not create an ephemeral encryption key"
fi
if ! fingerprint=$(gpg --no-options --homedir "$GNUPGHOME" --batch --with-colons --list-keys "$key_user_id" 2>"${WORK_DIR%/}/gpg-list.stderr" | awk -F: '$1 == "fpr" { print $10; exit }'); then
  fail "could not read the ephemeral key fingerprint"
fi
if [[ ! "$fingerprint" =~ ^[[:xdigit:]]{40,64}$ ]]; then
  fail "ephemeral key fingerprint is invalid"
fi

encrypted_file="${WORK_DIR%/}/backup.dump.gpg"
cat >"${MOCK_BIN%/}/oci" <<'MOCK_OCI'
#!/usr/bin/env bash
set -Eeuo pipefail
[[ "${1:-}" == "os" && "${2:-}" == "object" && "${3:-}" == "put" ]]
shift 3
name=""
file=""
bucket=""
profile=""
checksum=0
no_overwrite=0
while (($#)); do
  case "$1" in
    --name) name="$2"; shift 2 ;;
    --file) file="$2"; shift 2 ;;
    --bucket-name) bucket="$2"; shift 2 ;;
    --profile) profile="$2"; shift 2 ;;
    --verify-checksum) checksum=1; shift ;;
    --no-overwrite) no_overwrite=1; shift ;;
    --namespace-name|--region) shift 2 ;;
    *) exit 94 ;;
  esac
done
[[ "$bucket" == "dusema-staging-backups" && "$profile" == "ci-test" ]]
[[ "$name" == "backup-sets/${BACKUP_SET_ID}/postgres.dump.gpg" ]]
[[ -s "$file" && "$checksum" == 1 && "$no_overwrite" == 1 ]]
cp -- "$file" "$MOCK_POSTGRES_CAPTURE"
printf '%s\n' "$name" >"$MOCK_POSTGRES_OBJECT_NAME"
MOCK_OCI
chmod 0700 -- "${MOCK_BIN%/}/oci" || fail "could not prepare the mocked OCI client"

BACKUP_SET_ID="$(date -u '+%Y%m%dT%H%M%SZ')-$(od -An -N8 -tx1 /dev/urandom | tr -d '[:space:]')"
log "backup: creating a coordinated PostgreSQL ciphertext from the synthetic database"
if ! BACKUP_SET_ID="$BACKUP_SET_ID" \
  BACKUP_SET_ENVIRONMENT=staging \
  BACKUP_SET_ISOLATED_CONFIRMED=true \
  BACKUP_SET_WRITES_QUIESCED=true \
  BACKUP_SET_PG_CONTAINER="$POSTGRES_SERVICE_ID" \
  BACKUP_SET_PG_DATABASE="$SOURCE_DATABASE" \
  BACKUP_SET_PG_ROLE=postgres \
  BACKUP_SET_TMP_PARENT="$WORK_DIR" \
  BACKUP_SET_METADATA_FILE="${WORK_DIR%/}/postgres-metadata.json" \
  GNUPGHOME="$GNUPGHOME" \
  RECOVERY_RECIPIENT_FINGERPRINT="$fingerprint" \
  OCI_NAMESPACE=ci-test \
  OCI_BUCKET=dusema-staging-backups \
  OCI_REGION=ci-test-1 \
  OCI_OBJECT_PREFIX=backup-sets \
  OCI_UPLOAD_PROFILE=ci-test \
  OCI_CLI="${MOCK_BIN%/}/oci" \
  MOCK_POSTGRES_CAPTURE="$MOCK_POSTGRES_CAPTURE" \
  MOCK_POSTGRES_OBJECT_NAME="${WORK_DIR%/}/postgres-object-name" \
  bash deploy/postgres-backup/backup-set-postgres-artifact.sh; then
  fail "coordinated PostgreSQL backup artifact failed"
fi
encrypted_file="$MOCK_POSTGRES_CAPTURE"
if [[ ! -s "$encrypted_file" || "$(cat "${WORK_DIR%/}/postgres-object-name")" != "backup-sets/${BACKUP_SET_ID}/postgres.dump.gpg" ]]; then
  fail "mocked OCI did not capture the expected PostgreSQL set artifact"
fi
if ! python3 - "$WORK_DIR/postgres-metadata.json" "$encrypted_file" "$BACKUP_SET_ID" <<'PY'
import hashlib
import json
import pathlib
import sys

metadata_path = pathlib.Path(sys.argv[1])
artifact_path = pathlib.Path(sys.argv[2])
backup_set_id = sys.argv[3]
artifact_bytes = artifact_path.stat().st_size
expected = {
    "backup_set_id": backup_set_id,
    "artifact_type": "postgres",
    "key": f"backup-sets/{backup_set_id}/postgres.dump.gpg",
    "bytes": artifact_bytes,
    "sha256": hashlib.sha256(artifact_path.read_bytes()).hexdigest(),
}
if json.loads(metadata_path.read_text(encoding="utf-8")) != expected:
    raise SystemExit("artifact metadata does not match the uploaded PostgreSQL ciphertext")
PY
then
  fail "PostgreSQL artifact metadata does not match the uploaded ciphertext"
fi

if ! checksum_output=$(sha256sum -- "$encrypted_file" 2>/dev/null); then
  fail "could not calculate encrypted artifact checksum"
fi
encrypted_sha256="${checksum_output%% *}"
if [[ ! "$encrypted_sha256" =~ ^[[:xdigit:]]{64}$ ]]; then
  fail "encrypted artifact checksum is invalid"
fi

log "restore: rejecting a decrypted dump above the configured output cap"
if RECOVERY_GNUPGHOME="$GNUPGHOME" \
  ENCRYPTED_BACKUP_FILE="$encrypted_file" \
  EXPECTED_CIPHERTEXT_SHA256="$encrypted_sha256" \
  RESTORE_CONTAINER_ID="$TARGET_CONTAINER_ID" \
  RESTORE_DATABASE="$TARGET_DATABASE" \
  RESTORE_TMP_ROOT="$WORK_ROOT" \
  RESTORE_MAX_DECRYPTED_BYTES=1 \
  bash deploy/postgres-backup/restore-postgres-backup.sh \
  >"${WORK_DIR%/}/bounded-restore.log" 2>&1; then
  fail "one-byte decrypted-output cap unexpectedly accepted the synthetic dump"
fi
bounded_database_count=$(docker exec "$TARGET_CONTAINER_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname postgres \
  --command "SELECT count(*) FROM pg_catalog.pg_database WHERE datname = '${TARGET_DATABASE}';" \
  2>"${WORK_DIR%/}/bounded-database-check.stderr") || fail "could not verify bounded restore left no database"
if [[ "$bounded_database_count" != "0" ]]; then
  fail "bounded restore created a database despite rejecting the dump"
fi

log "restore: running the recovery command in the network-isolated target"
if ! RECOVERY_GNUPGHOME="$GNUPGHOME" \
  ENCRYPTED_BACKUP_FILE="$encrypted_file" \
  EXPECTED_CIPHERTEXT_SHA256="$encrypted_sha256" \
  RESTORE_CONTAINER_ID="$TARGET_CONTAINER_ID" \
  RESTORE_DATABASE="$TARGET_DATABASE" \
  RESTORE_TMP_ROOT="$WORK_ROOT" \
  bash deploy/postgres-backup/restore-postgres-backup.sh; then
  fail "isolated recovery command failed"
fi

state_query=$(cat <<'SQL'
SELECT concat_ws(':',
  count(*)::text,
  md5(COALESCE(string_agg(
    id::text || '|' || label || '|' || metadata::text || '|' || encode(payload, 'hex') || '|' ||
      to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US'),
    E'\n' ORDER BY id), '')),
  (SELECT last_value::text FROM restore_probe_id_seq),
  (SELECT is_called::text FROM restore_probe_id_seq)
)
FROM restore_probe;
SQL
)
if ! source_state=$(docker exec "$POSTGRES_SERVICE_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname "$SOURCE_DATABASE" --command "$state_query" 2>"${WORK_DIR%/}/source-state.stderr"); then
  fail "could not read synthetic source state"
fi
if ! restored_state=$(docker exec "$TARGET_CONTAINER_ID" psql --no-psqlrc --quiet --tuples-only --no-align \
  --username postgres --dbname "$TARGET_DATABASE" --command "$state_query" 2>"${WORK_DIR%/}/restored-state.stderr"); then
  fail "could not read restored database state"
fi
if [[ -z "$source_state" || "$source_state" != "$restored_state" ]]; then
  fail "restored row digest or sequence state does not match the source"
fi

log "PASS: encrypted PostgreSQL 17 backup restored; row digest and sequence state match"
